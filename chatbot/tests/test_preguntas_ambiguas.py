CASOS_NIVEL_2 = [c for c in CASOS_AMBIGUOS if c.get("nivel2")]


class TestNivel2SintesisLlama:
    """Ejecuta casos representativos de RAG sobre Llama 3.1 verificando desambiguación, formato TTS y 0 alucinaciones."""

    @pytest.mark.parametrize("caso", CASOS_NIVEL_2, ids=lambda c: f"{c['id']}:{c['pregunta'][:40]}")
    def test_nivel2_sintesis_y_formato(self, caso):
        with patch("app.generar_audio_hibrido") as mock_tts:
            resp = app.procesar_logica_hibrida(caso["pregunta"], idioma="es")
            assert not mock_tts.called

        resp_limpia = resp.strip()
        resp_norm = norm(resp_limpia)
        print(f"\n[{caso['id']}] {caso['pregunta']} -> {resp_limpia}")

        # 1. Validación estricta de formato TTS (1 párrafo, sin listas ni asteriscos, sin preguntas al final)
        assert "\n" not in resp_limpia, f"[{caso['id']}] La respuesta contiene saltos de línea:\n{resp_limpia}"
        assert "*" not in resp_limpia, f"[{caso['id']}] La respuesta contiene asteriscos:\n{resp_limpia}"
        assert "$" not in resp_limpia, f"[{caso['id']}] La respuesta contiene símbolo '$':\n{resp_limpia}"
        assert not resp_limpia.endswith("?"), f"[{caso['id']}] Prohibido terminar con pregunta al visitante:\n{resp_limpia}"
        assert not re.search(r'(?i)\b(a\.?\s*m\.?|p\.?\s*m\.?|de la mañana|de la tarde|de la noche)\b', resp_limpia), (
            f"[{caso['id']}] Horario no normalizado a 24h:\n{resp_limpia}"
        )

        # 2. Máximo 4 oraciones (tolerando abreviaturas comunes si existieran)
        oraciones = [o.strip() for o in re.split(r'(?<!\d)\.(?!\d)\s+', resp_limpia) if o.strip()]
        assert len(oraciones) <= 4, f"[{caso['id']}] Excede 4 oraciones ({len(oraciones)}):\n{resp_limpia}"

        # 3. Regla de Cero Alucinaciones para datos faltantes vs Datos presentes esperados
        if caso.get("esperar_dato_faltante"):
            assert any(k in resp_norm for k in ["no cuento con", "registros oficiales", "no menciona", "especifica", "informacion especifica"]), (
                f"[{caso['id']}] Debió declarar falta de dato oficial en lugar de alucinar:\n{resp_limpia}"
            )
        elif caso.get("esperar_ninguna_proteccion"):
            assert any(k in resp_norm for k in ["ninguna categoria", "no se encuentra en ninguna", "no cuento con", "registros oficiales"]), (
                f"[{caso['id']}] Debió indicar que no tiene categoría de protección o falta de dato oficial:\n{resp_limpia}"
            )
        else:
            # Al menos los conceptos esenciales del ground truth deben aparecer en la síntesis
            for forb in caso.get("datos_prohibidos", []):
                assert norm(forb) not in resp_norm, (
                    f"[{caso['id']}] Contaminación en respuesta LLM con '{forb}':\n{resp_limpia}"
                )
